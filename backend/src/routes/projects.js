import { Router } from 'express';
import * as controller from '../controllers/projects.js';
import { allowRoles } from '../middleware/auth.js';
const router = Router();
router.get('/export', controller.handleGetExport);
router.get('/', controller.handleGetRoot);
router.post('/', allowRoles('admin', 'project_manager'), controller.handlePostRoot);
router.get('/:projectId', controller.handleGetRoot2);
router.get('/:projectId/subtasks', allowRoles('admin', 'project_manager', 'worker'), controller.handleGetSubtasks);
router.get('/:projectId/subtasks/:subtaskId', allowRoles('admin', 'project_manager', 'worker'), controller.handleGetSubtasks2);
router.get('/:projectId/subtasks/:subtaskId/materials', allowRoles('admin', 'project_manager', 'worker'), controller.handleGetSubtasksMaterials);
router.get('/:projectId/subtasks/:subtaskId/materials/:materialId', allowRoles('admin', 'project_manager', 'worker'), controller.handleGetSubtasksMaterials2);
router.post('/:projectId/subtasks/:subtaskId/materials', allowRoles('admin', 'project_manager'), controller.handlePostSubtasksMaterials);
router.patch('/:projectId/subtasks/:subtaskId/materials/:materialId', allowRoles('admin', 'project_manager'), controller.handlePatchSubtasksMaterials);
router.delete('/:projectId/subtasks/:subtaskId/materials/:materialId', allowRoles('admin', 'project_manager'), controller.handleDeleteSubtasksMaterials);
router.post('/:projectId/subtasks', allowRoles('admin', 'project_manager'), controller.handlePostSubtasks);
router.patch('/:projectId/subtasks/:subtaskId', controller.handlePatchSubtasks);
router.delete('/:projectId/subtasks/:subtaskId', allowRoles('admin', 'project_manager'), controller.handleDeleteSubtasks);
router.patch('/:projectId', allowRoles('admin', 'project_manager'), controller.handlePatchRoot);
router.post('/:projectId/assign', allowRoles('admin', 'project_manager'), controller.handlePostAssign);
router.post('/:projectId/restore', allowRoles('admin'), controller.handlePostRestore);
router.delete('/:projectId', allowRoles('admin', 'project_manager'), controller.handleDeleteRoot);
router.post('/:projectId/accept', allowRoles('worker'), controller.handlePostAccept);
export default router;
